function homeSubtypeFromTitle(title: string, index: number): string {
  const t = title.toLowerCase();
  if (t.includes("flat") || t.includes("apartment")) return "FLAT";
  if (t.includes("penthouse")) return "PENTHOUSE";
  if (t.includes("farm")) return "FARM_HOUSE";
  if (t.includes("upper")) return "UPPER_PORTION";
  if (t.includes("lower") || t.includes("portion")) return "LOWER_PORTION";
  if (t.includes("room")) return "ROOM";
  const fallback = ["HOUSE", "FLAT", "PENTHOUSE", "HOUSE", "FLAT", "HOUSE"] as const;
  return fallback[index % fallback.length]!;
}

